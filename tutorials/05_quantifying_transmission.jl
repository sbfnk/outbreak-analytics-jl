md"""
# Quantifying Transmission

The transmission intensity of an outbreak is quantified using two key metrics:

- The **reproduction number** measures the *strength* of transmission — how many new cases each existing case generates on average.
- The **growth rate** measures the *speed* of transmission — how rapidly the outbreak is spreading or declining, related to the doubling time (when growing) or halving time (when declining).

The **basic reproduction number** $R_0$ is the average number of secondary cases generated by a single infected individual in a fully susceptible population. It characterises the pathogen's intrinsic transmissibility.

The **effective reproduction number** $R_t$ accounts for changes over time: population immunity, behavioural changes, and interventions all affect how many secondary infections each case actually produces at time $t$.

- $R_t > 1$: epidemic is growing
- $R_t < 1$: epidemic is shrinking
- $R_t = 1$: epidemic is stable

To estimate these metrics from case data, we must account for delays between infection and reporting. The time-varying reproduction number $R_t$ is therefore not simply a ratio of case counts, but requires statistical estimation that properly handles these delays and the inherent stochasticity of transmission.

**EpiNow2.jl** uses a **Bayesian inference** framework to estimate $R_t$. It combines prior knowledge (expressed as prior distributions on parameters) with observed data (via the likelihood) to produce posterior distributions for $R_t$ and other quantities of interest. This naturally quantifies uncertainty in our estimates — rather than producing a single point estimate, we obtain a full distribution reflecting what the data tell us.

This tutorial covers:
1. Estimating $R_t$ from case data using **EpiNow2.jl**
2. Specifying delay distributions (generation time, reporting delays)
3. Interpreting the output

!!! warning "Computation time"
    MCMC sampling takes several minutes. Be patient while the model runs.
"""

# ╔═╡ 2a3b4c5d-6e7f-8a9b-0c1d-2e3f4a5b6d01
md"""
## The data

In an outbreak situation, data are usually available on reported dates only — we rarely know the true date of infection. We must therefore use estimation methods that account for delays between infection and reporting when trying to understand changes in transmission over time.

Here we use synthetic case data built into EpiNow2.jl — 60 days of daily confirmed cases generated from a renewal process with time-varying $R_t$:
"""

# ╔═╡ 3a4b5c6d-7e8f-9a0b-1c2d-3e4f5a6b7d01
cases = example_confirmed()

# ╔═╡ 4a5b6c7d-8e9f-0a1b-2c3d-4e5f6a7b8d01
let

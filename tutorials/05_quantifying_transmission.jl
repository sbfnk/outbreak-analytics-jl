    ax = Axis(fig[1, 1]; xlabel="Date", ylabel="Confirmed cases",
              title="Daily confirmed cases")
    barplot!(ax, 1:nrow(cases), cases.confirm; color=(:steelblue, 0.7))
    ax.xticks = (1:10:nrow(cases), string.(cases.date[1:10:end]))
    ax.xticklabelrotation = π/4
    fig
end

# ╔═╡ 5a5b6c7d-8e9f-0a1b-2c3d-5e5f6a7b8d01
md"""
## Specifying delay distributions

To estimate $R_t$, EpiNow2 needs to know about the delays involved in the observation process. Why distributions rather than point estimates? The delay from infection to report involves multiple biological and administrative processes, each with individual-level variation. We capture this variation with probability distributions rather than fixed values, which properly propagates uncertainty into our $R_t$ estimates.

The key delays are:

1. **Generation time** — the delay between infection of a primary case and
   infection of a secondary case. This determines the timescale of transmission.
2. **Reporting delays** (optional) — incubation period + time from symptom onset
   to case confirmation. These determine how reported cases relate to the
   underlying infection process.

The delay from infection to report is composed of multiple stages: infection → symptom onset (the **incubation period**) followed by symptom onset → case notification (the **reporting delay**). Since delays cannot be negative, we use distributions defined on positive values only, such as the Gamma or LogNormal distributions.

Which delays you need depends on the data source:

| Data source | Delay(s) needed |
|---|---|
| Time of symptom onset | Incubation period |
| Time of case report | Incubation period + reporting delay |
| Time of hospitalisation | Incubation period + onset-to-hospitalisation |

We specify these as discretised probability distributions.

### Generation time

Let's use a LogNormal generation time with mean ≈ 3.6 days:
"""

# ╔═╡ 6a7b8c9d-0e1f-2a3b-4c5d-6e7f8a9b0d01
generation_time = discretise(LogNormal(1.2, 0.5); max=14)

# ╔═╡ 7a8b9c0d-1e2f-3a4b-5c6d-7e8f9a0b1d01
md"""
### Incubation period + reporting delay

We can compose delays with `+`:
"""

# ╔═╡ 8a9b0c1d-2e3f-4a5b-6c7d-8e9f0a1b2d01
begin
    incubation = discretise(LogNormal(1.4, 0.4); max=14)
    reporting = discretise(LogNormal(0.5, 0.5); max=7)
    total_delay = incubation + reporting
end

# ╔═╡ 9a0b1c2d-3e4f-5a6b-7c8d-9e0f1a2b3d01
md"""
## Running the estimation

Now we call `epinow()` — the main entry point. We use lighter inference settings
for this tutorial (fewer samples and chains):
"""

# ╔═╡ aa1b2c3d-4e5f-6a7b-8c9d-ae1f2a3b4d01
result = epinow(cases;
    generation_time = gt_opts(generation_time),
    delays = delay_opts(total_delay),
    rt = rt_opts(prior=LogNormal(log(1.0), 1.0)),
    inference = inference_opts(samples=1000, warmup=200, chains=2,
                               progress=false),
    verbose = false)

# ╔═╡ ab1b2c3d-4e5f-6a7b-8c9d-ab1f2a3b4d01
md"""
EpiNow2 performs Bayesian inference using Markov chain Monte Carlo (MCMC) methods via Turing.jl. Under the hood, the model uses a **renewal equation** to link infections over time through the generation time distribution: the expected number of new infections on each day is the sum of past infections weighted by the generation time probability mass function, scaled by $R_t$. A **Gaussian process** is used to smooth $R_t$ over time, preventing implausibly rapid changes while still allowing it to capture genuine trends.

Running multiple MCMC chains (as we did above with `chains=2`) helps assess whether the sampler has converged — if chains starting from different initial values reach similar posterior distributions, we can be more confident in the results.
"""

# ╔═╡ ba2b3c4d-5e6f-7a8b-9c0d-be2f3a4b5d01
md"""
## Interpreting the results

The result contains estimates of $R_t$, infections, and predicted reports, each as a DataFrame with credible intervals.

The output estimates are split into three categories:

- **Estimate**: based on complete data — all delays have had time to resolve, so these are the most reliable estimates.
- **Estimate based on partial data**: recent time points where some infections that occurred may not yet have been reported. These estimates have higher uncertainty because the most recent infections are least likely to have been observed.
- **Forecast**: projections into the future assuming $R_t$ remains constant at its most recent estimated value.

The uncertainty in the estimates naturally grows towards the end of the time series, reflecting the fact that recent data are incomplete:
"""

# ╔═╡ ca3b4c5d-6e7f-8a9b-0c1d-ce3f4a5b6d01
result.estimates.rt

# ╔═╡ da4b5c6d-7e8f-9a0b-1c2d-de4f5a6b7d01
md"""
### Reproduction number over time
"""

# ╔═╡ ea5b6c7d-8e9f-0a1b-2c3d-ee5f6a7b8d01
let
    rt = result.estimates.rt
    fig = Figure(size=(700, 350))
    ax = Axis(fig[1, 1]; xlabel="Date", ylabel="Rt",
              title="Time-varying reproduction number")

    dates_idx = 1:nrow(rt)

    # 90% CrI
    band!(ax, dates_idx, rt.lower_90, rt.upper_90; color=(:steelblue, 0.15))
    # 50% CrI
    band!(ax, dates_idx, rt.lower_50, rt.upper_50; color=(:steelblue, 0.3))
    # Median
    lines!(ax, dates_idx, rt.median; linewidth=2, color=:steelblue)

    hlines!(ax, [1.0]; color=:red, linestyle=:dash, linewidth=1.5)
    text!(ax, nrow(rt), 1.02; text="Rt = 1", align=(:right, :bottom),
          fontsize=10, color=:red)

    ax.xticks = (1:10:nrow(rt), string.(rt.date[1:10:end]))
    ax.xticklabelrotation = π/4

    fig
end

# ╔═╡ eb5b6c7d-8e9f-0a1b-2c3d-eb5f6a7b8d01
md"""
In all EpiNow2 output figures, the shaded regions represent **credible intervals** — darker shading indicates higher confidence. The 50% credible interval (darker band) contains the most likely values, whilst the 90% credible interval (lighter band) captures most of the uncertainty. The dashed red line at $R_t = 1$ marks the threshold between a growing and a shrinking epidemic.
"""

# ╔═╡ fa6b7c8d-9e0f-1a2b-3c4d-fe6f7a8b9d01
md"""
### Estimated infections vs reported cases
"""


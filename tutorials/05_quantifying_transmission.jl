# ╔═╡ 1b8b9c0d-1e2f-3a4b-5c6d-1f8f9a0b1d01
md"""
## Using delay distributions from the literature

Instead of specifying delays manually, we can pull them from `EpiParameters.jl`. Using literature-sourced delay distributions is particularly valuable early in an outbreak, when local data on delays may not yet be available — published estimates from previous outbreaks or other settings provide a reasonable starting point.

```julia
using EpiParameters

# Get COVID-19 generation time from the literature
gt_results = epiparameter(disease="COVID-19", epi_name="serial interval")
gt_dist = filter(p -> !isnothing(p.distribution), gt_results)[1].distribution

# Discretise and use in EpiNow2
generation_time = discretise(gt_dist; max=14)
result = epinow(cases; generation_time=gt_opts(generation_time), ...)
```

The next tutorial covers this workflow in detail.
"""

# ╔═╡ 2b9b0c1d-2e3f-4a5b-6c7d-2f9f0a1b2d01
md"""
## Key points

- **$R_t$** measures whether an epidemic is growing ($R_t > 1$) or shrinking ($R_t < 1$)
- **EpiNow2.jl** estimates $R_t$ using a Bayesian renewal equation model with
  Gaussian process smoothing, fitted via MCMC (Turing.jl)
- You must specify a **generation time** distribution; reporting delays are optional
  but improve estimates
- Delays can be **composed** with `+` (e.g. incubation + reporting)
- Output includes **credible intervals** — always report uncertainty
- Use `EpiParameters.jl` to get delay distributions from the literature rather
  than guessing
"""

